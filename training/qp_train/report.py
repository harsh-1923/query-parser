"""One-command eval report (PLAN §14, M3): every test set × the rule tagger and any trained runs.

    uv run python -m qp_train.report [--run medium=runs/s1b/tagger-medium ...]

or `pnpm eval` from the repo root. Writes eval/results/report.md and report.json. Test sets that
don't exist (handwritten, not yet labelled; generated, not regenerated) are skipped.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import tempfile
from pathlib import Path

from .data import Labels, load_jsonl
from .metrics import score

ROOT = Path(__file__).resolve().parents[2]
TEST_SETS = {
    "S02 (Haiku)": "eval/datasets/llm-written/v0/bio.jsonl",
    "GLM v1": "eval/datasets/llm-written/v1/bio.jsonl",
    "handwritten": "eval/datasets/handwritten/bio.jsonl",
    "generated v1": "eval/datasets/generated/v1/test.jsonl",
}
ROLES = ["ACTOR", "TIME", "KIND", "ATTR", "CONTAINER", "TOPIC", "ORDER", "NEG"]


def rule_predictions(path: Path) -> list[list[str]]:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "pred.jsonl"
        subprocess.run(
            ["node", str(ROOT / "eval/rule-predict.ts"), str(path), str(out)],
            check=True,
            capture_output=True,
        )
        return [json.loads(line)["tags"] for line in out.read_text().splitlines() if line.strip()]


def model_predictor(run: str, labels: Labels):
    import torch  # only when a run is given

    from .evaluate import predict_all
    from .runs import load_run

    torch.manual_seed(0)
    model, meta = load_run(run, labels)
    return meta["params"], lambda examples: predict_all(model, examples, labels)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--run", action="append", default=[], help="name=path to a trained run")
    p.add_argument("--out", default=str(ROOT / "eval/results/report"))
    args = p.parse_args()

    labels = Labels.load()
    systems = {"rules": (None, None)}
    for spec in args.run:
        name, _, path = spec.partition("=")
        systems[name] = model_predictor(path, labels)

    report: dict = {"systems": {k: {"params": v[0]} for k, v in systems.items()}, "sets": {}}
    for set_name, rel in TEST_SETS.items():
        path = ROOT / rel
        if not path.exists():
            continue
        examples = load_jsonl(str(path), labels)
        report["sets"][set_name] = {"path": rel, "n": len(examples), "results": {}}
        for sys_name, (_, predict) in systems.items():
            pred = rule_predictions(path) if predict is None else predict(examples)
            r = score(examples, pred)
            report["sets"][set_name]["results"][sys_name] = {
                "f1": r["overall"]["f1"],
                "p": r["overall"]["p"],
                "r": r["overall"]["r"],
                "exact_match": r["exact_match"],
                "per_role": {k: v["f1"] for k, v in r["per_role"].items()},
                "names_without_cue": r.get("names_without_cue", {}).get("f1"),
            }

    out = Path(args.out)
    out.with_suffix(".json").write_text(json.dumps(report, indent=2) + "\n")
    out.with_suffix(".md").write_text(markdown(report))
    print(markdown(report))
    print(f"wrote {out.with_suffix('.md')} and .json")


def markdown(report: dict) -> str:
    def f(x: float | None) -> str:
        return "–" if x is None else f"{x:.3f}"

    lines = [
        "# Eval report",
        "",
        "Generated by `pnpm eval`. Span F1 counts exact role and boundaries.",
        "",
        "| Test set | n | System | Span F1 | P | R | Exact match | Names, no cue |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for set_name, s in report["sets"].items():
        for sys_name, r in s["results"].items():
            lines.append(
                f"| {set_name} | {s['n']} | {sys_name} | {f(r['f1'])} | {f(r['p'])} | {f(r['r'])}"
                f" | {f(r['exact_match'])} | {f(r['names_without_cue'])} |"
            )
    lines += ["", "## Span F1 by role", ""]
    lines.append("| Test set | System | " + " | ".join(ROLES) + " |")
    lines.append("|---|---|" + "---|" * len(ROLES))
    for set_name, s in report["sets"].items():
        for sys_name, r in s["results"].items():
            cells = [f(r["per_role"].get(role)) for role in ROLES]
            lines.append(f"| {set_name} | {sys_name} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main()
